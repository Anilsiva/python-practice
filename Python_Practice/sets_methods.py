# Sets Intersection: Write Python code to find and print the intersection of the following two sets
set1 = {1, 2, 3, 4, 5}
set2 = {4, 5, 6, 7, 8}
set3 = set1.intersection(set2)
print(set3)

# Sets Union: Write Python code to find and print the union of the following two sets
set1 = {1, 2, 3, 4, 5}
set2 = {4, 5, 6, 7, 8}
set3 = set1.union(set2)
print(set3)

# Set Difference: Write Python code to find and print the elements present in set1 but not in set2
